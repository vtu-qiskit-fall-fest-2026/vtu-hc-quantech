"""Test suite for Phase 2 (Learning Context) and Phase 3 (Topic/Concept-Aware Retrieval & Boundaries)."""
import os
import sys

# Ensure project root is in sys.path
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from backend.knowledge.registry import get_topic_registry
from backend.knowledge.retriever import TopicRetriever
from fastapi.testclient import TestClient
from backend.main import app

def test_retrieval_and_boundaries():
    registry = get_topic_registry()
    retriever = TopicRetriever(registry)
    print("\n--- TEST 1: Topic 1.3 Deictic Query ('Explain this in simpler terms') ---")
    res = retriever.retrieve(
        query="Explain this in simpler terms",
        current_topic_id="1.3",
        concept_id="C02",
        learning_context={
            "topic_id": "1.3",
            "concept_id": "C02",
            "concept_title": "Simulating Nature (Molecules and Materials)"
        }
    )
    print(f"Primary Concept: {res.primary_concept.title if res.primary_concept else None} (ID: {res.primary_concept.id if res.primary_concept else None})")
    print(f"Topic ID: {res.topic_id}")
    print(f"Is Out of Scope: {res.is_out_of_scope}")
    print(f"Sources: {res.sources}")

    assert res.primary_concept is not None, "Primary concept should be resolved"
    assert res.primary_concept.id == "C02", f"Expected concept C02, got {res.primary_concept.id}"
    assert not res.is_out_of_scope, "Deictic query on active concept must NOT be out of scope"
    for s in res.sources:
        assert s["topic_id"] == "1.3", f"Boundary violation: retrieved source from topic {s['topic_id']} instead of 1.3"
    print("✓ TEST 1 PASSED: Strict Topic 1.3 boundary respected, concept C02 resolved directly!")

    print("\n--- TEST 2: 'What am I looking at?' with visible_visual ---")
    visual_meta = {
        "id": "chem_sim_diagram",
        "title": "Molecular Energy Surface",
        "type": "energy_diagram",
        "caption": "Ground state energy calculation for hydrogen molecule.",
        "description": "Shows the exponential scaling of electron configuration basis states vs quantum superposition representation."
    }
    res2 = retriever.retrieve(
        query="What am I looking at?",
        current_topic_id="1.3",
        concept_id="C02",
        visible_visual=visual_meta,
        learning_context={
            "topic_id": "1.3",
            "concept_id": "C02",
            "visible_visual": visual_meta
        }
    )
    print(f"Visual retrieved in sources: {[s for s in res2.sources if s['type'] == 'visual']}")
    print(f"Retrieved Chunks Count: {len(res2.retrieved_chunks)}")
    print(f"First chunk preview: {res2.retrieved_chunks[0][:120]}...")
    assert any(s["type"] == "visual" for s in res2.sources), "Visual source must be registered"
    assert "Molecular Energy Surface" in res2.retrieved_chunks[0], "Visual description must be in first chunk"
    assert not res2.is_out_of_scope, "Visual explanation must not be out of scope"
    print("✓ TEST 2 PASSED: Active visual dynamically captured and placed in prompt context!")

    print("\n--- TEST 3: FastAPI /tutor/ask with learning_context payload ---")
    client = TestClient(app)
    payload = {
        "question": "Can you explain this simply?",
        "learning_context": {
            "route": "/learn",
            "module_id": "module-1",
            "topic_id": "1.3",
            "topic_title": "Quantum Computing Applications",
            "concept_id": "C02",
            "concept_title": "Simulating Nature",
            "visible_visual": visual_meta
        }
    }
    r = client.post("/api/tutor/ask", json=payload)
    assert r.status_code == 200, f"Expected 200, got {r.status_code}: {r.text}"
    data = r.json()
    print(f"Tutor Answer Length: {len(data['answer'])}")
    print(f"Generated By: {data['generated_by']}")
    print(f"Verified: {data['verified']}")
    print(f"Topic ID: {data['topic_id']}")
    print(f"Sources: {data['sources']}")
    assert data["topic_id"] == "1.3", f"Expected topic 1.3, got {data['topic_id']}"
    assert any(s["topic_id"] == "1.3" for s in data["sources"]), "Sources must be grounded in Topic 1.3"
    print("✓ TEST 3 PASSED: /tutor/ask ingests learning_context end-to-end!")

if __name__ == "__main__":
    test_retrieval_and_boundaries()
    print("\n=======================================================")
    print("  ALL PHASE 2 & PHASE 3 RETRIEVAL TESTS PASSED!")
    print("=======================================================\n")
